let currentLang = "en";

function t(key) {
  const dict = I18N_TRANSLATIONS[currentLang] || I18N_TRANSLATIONS.en;
  return dict[key] || I18N_TRANSLATIONS.en[key] || key;
}

function setLanguage(lang) {
  if (I18N_TRANSLATIONS[lang]) {
    currentLang = lang;
    document.documentElement.lang = lang;
    window.dispatchEvent(new CustomEvent("grexa:langChange", { detail: { lang } }));
  }
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { I18N_TRANSLATIONS, t, setLanguage };
}
